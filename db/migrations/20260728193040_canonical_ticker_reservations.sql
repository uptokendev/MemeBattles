create table if not exists public.ticker_reservations (
  id uuid primary key default gen_random_uuid(),
  draft_id uuid references public.campaign_drafts(id) on delete set null,
  creator_wallet text not null,
  chain_id integer not null,
  cluster text not null,
  original_ticker text not null,
  normalized_ticker text not null,
  ticker_hash text not null,
  reservation_id_hash text not null,
  status text not null,
  reserved_at timestamptz not null default now(),
  published_at timestamptz,
  expires_at timestamptz,
  grace_end_at timestamptz,
  renewal_count smallint not null default 0,
  scheduled_launch_at timestamptz,
  arm_authorized_at timestamptz,
  arming_at timestamptz,
  armed_at timestamptz,
  live_at timestamptz,
  schedule_missed_at timestamptz,
  released_at timestamptz,
  program_id text,
  generation_id text,
  campaign_pda text,
  mint text,
  deployment_signature text,
  reservation_version bigint not null default 1,
  authorization_nonce text,
  failure_reason text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint ticker_reservations_chain_id_positive check (chain_id > 0),
  constraint ticker_reservations_cluster_present check (length(btrim(cluster)) between 1 and 80),
  constraint ticker_reservations_original_ticker_present check (length(btrim(original_ticker)) between 1 and 32),
  constraint ticker_reservations_normalized_ticker_valid check (normalized_ticker ~ '^[A-Z0-9]{1,12}$'),
  constraint ticker_reservations_ticker_hash_valid check (ticker_hash ~ '^[0-9a-f]{64}$'),
  constraint ticker_reservations_id_hash_valid check (reservation_id_hash ~ '^[0-9a-f]{64}$'),
  constraint ticker_reservations_status_valid check (status = any (array[
    'DRAFT_UNRESERVED',
    'SOFT_RESERVED',
    'PREPARE_MODE_RESERVED',
    'SCHEDULED_UNARMED',
    'ARM_AUTHORIZED',
    'ARMING',
    'ARMED_ONCHAIN',
    'LIVE',
    'DEPLOY_FAILED',
    'EXPIRED_GRACE',
    'RELEASED',
    'SCHEDULE_MISSED'
  ]::text[])),
  constraint ticker_reservations_renewal_count_valid check (renewal_count between 0 and 2),
  constraint ticker_reservations_version_positive check (reservation_version > 0),
  constraint ticker_reservations_grace_order check (
    expires_at is null or grace_end_at is null or grace_end_at >= expires_at
  )
);

comment on table public.ticker_reservations is
  'Canonical chain-scoped ticker reservation lifecycle. Server-only; Railway/API owns mutations.';
comment on column public.ticker_reservations.ticker_hash is
  'Lowercase hex SHA-256 of normalized_ticker. Chain-specific on-chain serializers may derive their required hash separately.';
comment on column public.ticker_reservations.reservation_version is
  'Monotonic version bound into create authorization; incremented when reservation terms change.';

create unique index if not exists ticker_reservations_blocking_ticker_uidx
  on public.ticker_reservations (chain_id, normalized_ticker)
  where status not in ('DRAFT_UNRESERVED', 'RELEASED');

create unique index if not exists ticker_reservations_blocking_draft_uidx
  on public.ticker_reservations (draft_id)
  where draft_id is not null and status not in ('DRAFT_UNRESERVED', 'RELEASED');

create unique index if not exists ticker_reservations_reservation_id_hash_uidx
  on public.ticker_reservations (reservation_id_hash);

create unique index if not exists ticker_reservations_campaign_pda_uidx
  on public.ticker_reservations (chain_id, campaign_pda)
  where campaign_pda is not null and campaign_pda <> '';

create unique index if not exists ticker_reservations_mint_uidx
  on public.ticker_reservations (chain_id, mint)
  where mint is not null and mint <> '';

create unique index if not exists ticker_reservations_deployment_signature_uidx
  on public.ticker_reservations (chain_id, deployment_signature)
  where deployment_signature is not null and deployment_signature <> '';

create index if not exists ticker_reservations_creator_history_idx
  on public.ticker_reservations (chain_id, creator_wallet, created_at desc);

create index if not exists ticker_reservations_expiry_idx
  on public.ticker_reservations (expires_at, grace_end_at)
  where status in (
    'SOFT_RESERVED',
    'PREPARE_MODE_RESERVED',
    'SCHEDULED_UNARMED',
    'DEPLOY_FAILED',
    'EXPIRED_GRACE',
    'SCHEDULE_MISSED'
  );

create index if not exists ticker_reservations_schedule_idx
  on public.ticker_reservations (scheduled_launch_at)
  where status in ('SCHEDULED_UNARMED', 'ARM_AUTHORIZED', 'ARMING', 'ARMED_ONCHAIN');

create table if not exists public.ticker_reservation_events (
  id bigint generated by default as identity primary key,
  reservation_id uuid not null references public.ticker_reservations(id) on delete cascade,
  event_type text not null,
  from_status text,
  to_status text,
  actor_type text not null default 'system',
  actor_wallet text,
  reason text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  constraint ticker_reservation_events_event_type_present check (length(btrim(event_type)) between 1 and 80),
  constraint ticker_reservation_events_actor_type_valid check (
    actor_type = any (array['system', 'migration', 'creator', 'route_signer', 'admin', 'indexer']::text[])
  )
);

comment on table public.ticker_reservation_events is
  'Append-only audit history for canonical ticker reservation lifecycle transitions.';

create index if not exists ticker_reservation_events_reservation_idx
  on public.ticker_reservation_events (reservation_id, created_at desc);

create index if not exists ticker_reservation_events_type_idx
  on public.ticker_reservation_events (event_type, created_at desc);

