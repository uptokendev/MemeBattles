with draft_source as (
  select
    gen_random_uuid() as reservation_id,
    d.id as draft_id,
    d.creator_wallet,
    d.chain_id,
    case
      when d.chain_id = 56 then 'bsc-mainnet'
      when d.chain_id = 97 then 'bsc-testnet'
      when d.chain_id in (101, 102) then 'solana-legacy-' || d.chain_id::text
      else 'chain-' || d.chain_id::text
    end as cluster,
    d.ticker as original_ticker,
    upper(left(regexp_replace(d.ticker, '[^A-Za-z0-9]', '', 'g'), 12)) as normalized_ticker,
    d.status as draft_status,
    d.visibility,
    d.created_at as draft_created_at,
    d.updated_at as draft_updated_at,
    d.deployed_at,
    d.scheduled_launch_at,
    d.campaign_address,
    d.token_address,
    d.deploy_tx_hash,
    p.published_at,
    c.factory_address
  from public.campaign_drafts d
  left join public.campaign_draft_promotion p on p.draft_id = d.id
  left join public.campaigns c
    on c.chain_id = d.chain_id
   and lower(c.campaign_address) = lower(coalesce(d.campaign_address, ''))
  where d.status <> 'archived'
),
draft_prepared as (
  select
    reservation_id,
    draft_id,
    creator_wallet,
    chain_id,
    cluster,
    original_ticker,
    normalized_ticker,
    encode(digest(normalized_ticker, 'sha256'), 'hex') as ticker_hash,
    encode(digest(reservation_id::text, 'sha256'), 'hex') as reservation_id_hash,
    case
      when campaign_address is not null and deploy_tx_hash is not null then
        case
          when scheduled_launch_at is null or scheduled_launch_at <= now() then 'LIVE'
          else 'ARMED_ONCHAIN'
        end
      when draft_status = 'scheduled' then 'SCHEDULED_UNARMED'
      when visibility = 'public' or draft_status in ('promotion_published', 'ready_to_launch') then 'PREPARE_MODE_RESERVED'
      else 'SOFT_RESERVED'
    end as reservation_status,
    coalesce(published_at, case when visibility = 'public' then draft_updated_at else null end) as effective_published_at,
    case
      when campaign_address is not null and deploy_tx_hash is not null then null
      when draft_status = 'scheduled' and scheduled_launch_at is not null then scheduled_launch_at
      when visibility = 'public' or draft_status in ('promotion_published', 'ready_to_launch') then now() + interval '14 days'
      else now() + interval '72 hours'
    end as effective_expires_at,
    scheduled_launch_at,
    deployed_at,
    campaign_address,
    token_address,
    deploy_tx_hash,
    factory_address,
    draft_status,
    visibility,
    draft_created_at,
    draft_updated_at
  from draft_source
  where normalized_ticker <> ''
),
inserted_drafts as (
  insert into public.ticker_reservations (
    id,
    draft_id,
    creator_wallet,
    chain_id,
    cluster,
    original_ticker,
    normalized_ticker,
    ticker_hash,
    reservation_id_hash,
    status,
    reserved_at,
    published_at,
    expires_at,
    grace_end_at,
    scheduled_launch_at,
    armed_at,
    live_at,
    program_id,
    campaign_pda,
    mint,
    deployment_signature,
    reservation_version,
    metadata
  )
  select
    reservation_id,
    draft_id,
    creator_wallet,
    chain_id,
    cluster,
    original_ticker,
    normalized_ticker,
    ticker_hash,
    reservation_id_hash,
    reservation_status,
    now(),
    effective_published_at,
    effective_expires_at,
    case when effective_expires_at is null then null else effective_expires_at + interval '24 hours' end,
    scheduled_launch_at,
    case when reservation_status in ('ARMED_ONCHAIN', 'LIVE') then coalesce(deployed_at, draft_updated_at) else null end,
    case when reservation_status = 'LIVE' then coalesce(scheduled_launch_at, deployed_at, draft_updated_at) else null end,
    factory_address,
    campaign_address,
    token_address,
    deploy_tx_hash,
    1,
    jsonb_build_object(
      'source', 'campaign_drafts_backfill',
      'draftStatus', draft_status,
      'visibility', visibility,
      'draftCreatedAt', draft_created_at,
      'draftUpdatedAt', draft_updated_at
    )
  from draft_prepared
  on conflict do nothing
  returning id, status, draft_id, chain_id, normalized_ticker
)
insert into public.ticker_reservation_events (
  reservation_id,
  event_type,
  from_status,
  to_status,
  actor_type,
  reason,
  metadata
)
select
  id,
  'migration_backfill_draft',
  null,
  status,
  'migration',
  'Canonical ticker reservation created from an existing active draft.',
  jsonb_build_object('draftId', draft_id, 'chainId', chain_id, 'ticker', normalized_ticker)
from inserted_drafts;

with normalized_campaigns as (
  select
    c.chain_id,
    upper(left(regexp_replace(c.symbol, '[^A-Za-z0-9]', '', 'g'), 12)) as normalized_ticker,
    c.symbol,
    c.creator_address,
    c.campaign_address,
    c.token_address,
    c.factory_address,
    coalesce(c.created_at_chain, c.created_at, now()) as effective_created_at
  from public.campaigns c
  where coalesce(c.campaign_address, '') <> ''
    and coalesce(c.symbol, '') <> ''
),
campaign_groups as (
  select
    gen_random_uuid() as reservation_id,
    chain_id,
    normalized_ticker,
    (array_agg(symbol order by effective_created_at, campaign_address))[1] as original_ticker,
    coalesce(nullif((array_agg(creator_address order by effective_created_at, campaign_address))[1], ''), 'unknown') as creator_wallet,
    (array_agg(campaign_address order by effective_created_at, campaign_address))[1] as campaign_address,
    (array_agg(token_address order by effective_created_at, campaign_address))[1] as token_address,
    (array_agg(factory_address order by effective_created_at, campaign_address))[1] as factory_address,
    min(effective_created_at) as first_live_at,
    jsonb_agg(
      jsonb_build_object(
        'campaignAddress', campaign_address,
        'tokenAddress', token_address,
        'creatorAddress', creator_address,
        'factoryAddress', factory_address,
        'createdAt', effective_created_at
      )
      order by effective_created_at, campaign_address
    ) as campaign_instances
  from normalized_campaigns
  where normalized_ticker <> ''
  group by chain_id, normalized_ticker
),
inserted_campaigns as (
  insert into public.ticker_reservations (
    id,
    draft_id,
    creator_wallet,
    chain_id,
    cluster,
    original_ticker,
    normalized_ticker,
    ticker_hash,
    reservation_id_hash,
    status,
    reserved_at,
    live_at,
    program_id,
    campaign_pda,
    mint,
    reservation_version,
    metadata
  )
  select
    g.reservation_id,
    null,
    g.creator_wallet,
    g.chain_id,
    case
      when g.chain_id = 56 then 'bsc-mainnet'
      when g.chain_id = 97 then 'bsc-testnet'
      when g.chain_id in (101, 102) then 'solana-legacy-' || g.chain_id::text
      else 'chain-' || g.chain_id::text
    end,
    g.original_ticker,
    g.normalized_ticker,
    encode(digest(g.normalized_ticker, 'sha256'), 'hex'),
    encode(digest(g.reservation_id::text, 'sha256'), 'hex'),
    'LIVE',
    g.first_live_at,
    g.first_live_at,
    g.factory_address,
    g.campaign_address,
    g.token_address,
    1,
    jsonb_build_object(
      'source', 'campaigns_backfill',
      'campaignCount', jsonb_array_length(g.campaign_instances),
      'campaigns', g.campaign_instances
    )
  from campaign_groups g
  where not exists (
    select 1
    from public.ticker_reservations r
    where r.chain_id = g.chain_id
      and r.normalized_ticker = g.normalized_ticker
      and r.status not in ('DRAFT_UNRESERVED', 'RELEASED')
  )
  on conflict do nothing
  returning id, status, chain_id, normalized_ticker, metadata
)
insert into public.ticker_reservation_events (
  reservation_id,
  event_type,
  from_status,
  to_status,
  actor_type,
  reason,
  metadata
)
select
  id,
  'migration_backfill_live_campaign',
  null,
  status,
  'migration',
  'Canonical ticker lock created from existing live campaign data.',
  jsonb_build_object(
    'chainId', chain_id,
    'ticker', normalized_ticker,
    'campaignCount', metadata -> 'campaignCount'
  )
from inserted_campaigns;
